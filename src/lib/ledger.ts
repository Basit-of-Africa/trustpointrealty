import "server-only";
import { and, eq, inArray, isNull, ne, sql } from "drizzle-orm";
import type { DB } from "@/db";
import { getDb, schema } from "@/db";
import { commissionFor } from "@/lib/money";
import type { Sale } from "@/db/schema";

const { commissions, payouts, salePayments } = schema;

type Tx = Parameters<Parameters<DB["transaction"]>[0]>[0];

export type Balance = {
  pending: number; // earned, waiting for admin approval
  approved: number; // approved commissions (all time, net of clawbacks)
  paidOut: number; // logged payouts (not voided)
  available: number; // approved - paidOut = what the company owes now
};

/** Balances for one realtor, or for everyone when realtorIds is omitted. */
export async function getBalances(
  realtorIds?: string[],
  db: Pick<DB, "select"> = getDb(),
): Promise<Map<string, Balance>> {
  const commissionRows = await db
    .select({
      realtorId: commissions.realtorId,
      pending: sql<string>`coalesce(sum(${commissions.amount}) filter (where ${commissions.status} = 'pending'), 0)`,
      approved: sql<string>`coalesce(sum(${commissions.amount}) filter (where ${commissions.status} = 'approved'), 0)`,
    })
    .from(commissions)
    .where(realtorIds ? inArray(commissions.realtorId, realtorIds) : undefined)
    .groupBy(commissions.realtorId);

  const payoutRows = await db
    .select({
      realtorId: payouts.realtorId,
      paid: sql<string>`coalesce(sum(${payouts.amount}), 0)`,
    })
    .from(payouts)
    .where(
      and(
        isNull(payouts.voidedAt),
        realtorIds ? inArray(payouts.realtorId, realtorIds) : undefined,
      ),
    )
    .groupBy(payouts.realtorId);

  const map = new Map<string, Balance>();
  const get = (id: string) => {
    let b = map.get(id);
    if (!b) {
      b = { pending: 0, approved: 0, paidOut: 0, available: 0 };
      map.set(id, b);
    }
    return b;
  };
  for (const r of commissionRows) {
    const b = get(r.realtorId);
    b.pending = Number(r.pending);
    b.approved = Number(r.approved);
  }
  for (const r of payoutRows) get(r.realtorId).paidOut = Number(r.paid);
  for (const b of map.values()) b.available = b.approved - b.paidOut;
  for (const id of realtorIds ?? []) get(id);
  return map;
}

export async function getBalance(realtorId: string, db?: Pick<DB, "select">) {
  return (await getBalances([realtorId], db)).get(realtorId)!;
}

/** Total paid by the client on a sale (excluding reversed payments). */
export async function amountPaidOnSale(saleId: number, db: Pick<DB, "select"> = getDb()) {
  const [row] = await db
    .select({ total: sql<string>`coalesce(sum(${salePayments.amount}), 0)` })
    .from(salePayments)
    .where(and(eq(salePayments.saleId, saleId), isNull(salePayments.reversedAt)));
  return Number(row.total);
}

/**
 * Create the pending commission entries generated by a client payment:
 * one for the sale's realtor and, if set, one for their upline.
 */
export async function createCommissionsForPayment(
  tx: Tx,
  sale: Sale,
  paymentId: number,
  amount: number,
  actorId: string,
) {
  const rows: (typeof commissions.$inferInsert)[] = [];
  if (sale.realtorId && sale.commissionRateBps > 0) {
    rows.push({
      realtorId: sale.realtorId,
      kind: "direct",
      amount: commissionFor(amount, sale.commissionRateBps),
      rateBps: sale.commissionRateBps,
      saleId: sale.id,
      paymentId,
      createdById: actorId,
    });
  }
  if (sale.uplineId && sale.uplineRateBps > 0 && sale.uplineId !== sale.realtorId) {
    rows.push({
      realtorId: sale.uplineId,
      kind: "upline",
      amount: commissionFor(amount, sale.uplineRateBps),
      rateBps: sale.uplineRateBps,
      saleId: sale.id,
      paymentId,
      createdById: actorId,
    });
  }
  const nonZero = rows.filter((r) => r.amount !== 0);
  if (nonZero.length) await tx.insert(commissions).values(nonZero);
  return nonZero;
}

/**
 * Undo the commissions of a reversed client payment. Pending ones are
 * voided; approved ones get an approved negative "clawback" entry so the
 * history stays intact.
 */
export async function reverseCommissionsForPayment(
  tx: Tx,
  paymentId: number,
  actorId: string,
  reason: string,
) {
  const linked = await tx
    .select()
    .from(commissions)
    .where(
      and(
        eq(commissions.paymentId, paymentId),
        inArray(commissions.kind, ["direct", "upline"]),
        ne(commissions.status, "void"),
      ),
    );
  let voided = 0;
  let clawedBack = 0;
  for (const c of linked) {
    if (c.status === "pending") {
      await tx
        .update(commissions)
        .set({ status: "void", note: `Voided: ${reason}` })
        .where(eq(commissions.id, c.id));
      voided++;
    } else {
      await tx.insert(commissions).values({
        realtorId: c.realtorId,
        kind: "clawback",
        status: "approved",
        amount: -c.amount,
        saleId: c.saleId,
        paymentId: c.paymentId,
        reversesId: c.id,
        note: `Clawback: ${reason}`,
        approvedById: actorId,
        approvedAt: new Date(),
        createdById: actorId,
      });
      clawedBack++;
    }
  }
  return { voided, clawedBack };
}
